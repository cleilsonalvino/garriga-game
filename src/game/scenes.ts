export function getSceneById(sceneId: SceneId): SceneDefinition {
  return SCENES[sceneId] ?? SCENES.povoado_principal;
}

export function getPortalsForScene(sceneId: SceneId): ScenePortal[] {
  return SCENE_PORTALS.filter((p) => p.fromSceneId === sceneId);
}

export function findPortalBetween(
  fromSceneId: SceneId,
  toSceneId: SceneId
): ScenePortal | null {
  return (
    SCENE_PORTALS.find(
      (p) => p.fromSceneId === fromSceneId && p.toSceneId === toSceneId
    ) ?? null
  );
}
